        if recorderObj then
            pcall(function() recorderObj.stop() end)
            pcall(function() recorderObj.release() end)
            recorderObj = nil
        end
        isRecording = false
        isPaused = false
    end

    btn_audio_rec_toggle.onClick = function()
        if not isRecording then
            pcall(function()
                if audioFileObj.exists() then audioFileObj.delete() end
                local parentDir = audioFileObj.getParentFile()
                if parentDir and not parentDir.exists() then parentDir.mkdirs() end
            end)

            local recordSuccess, recordErr = pcall(function()
                if MediaRecorder then
                    recorderObj = MediaRecorder()
                elseif MediaRecorderClass then
                    recorderObj = MediaRecorderClass()
                end
                recorderObj.setAudioSource(1)
                recorderObj.setOutputFormat(2)
                recorderObj.setAudioEncoder(3)
                recorderObj.setOutputFile(audioFileObj.getAbsolutePath())
                recorderObj.prepare()
                recorderObj.start()
            end)

            if recordSuccess then
                isRecording = true
                isPaused = false
                btn_audio_rec_toggle.setText("Pause Recording")
                txt_audio_rec_status.setText("Recording voice... Speak now.")
                pcall(function() if service and service.speak then service.speak("Recording started. Speak now.") end end)
            else
                stopAndFreeRecorder()
                txt_audio_rec_status.setText("Microphone access failed.")
                notify("Microphone access failed. Please enable microphone permission in Settings.")
            end
        else
            if not isPaused then
                pcall(function() recorderObj.pause() end)
                isPaused = true
                btn_audio_rec_toggle.setText("Resume Recording")
                txt_audio_rec_status.setText("Recording paused.")
                pcall(function() if service and service.speak then service.speak("Recording paused.") end end)
            else
                pcall(function() recorderObj.resume() end)
                isPaused = false
                btn_audio_rec_toggle.setText("Pause Recording")
                txt_audio_rec_status.setText("Recording voice... Speak now.")
                pcall(function() if service and service.speak then service.speak("Recording resumed.") end end)
            end
        end
    end

    btn_audio_rec_discard.onClick = function()
        stopAndFreeRecorder()
        pcall(function()
            if audioFileObj.exists() then audioFileObj.delete() end
        end)
        btn_audio_rec_toggle.setText("Start Voice Recording")
        txt_audio_rec_status.setText("Recording discarded.")
        pcall(function() if service and service.speak then service.speak("Recording discarded.") end end)
    end

    btn_audio_rec_send_wa.onClick = function()
        if isRecording then stopAndFreeRecorder() end

        if not audioFileObj.exists() or audioFileObj.length() <= 1024 then
            notify("Voice note is empty. Please record your voice before sending.")
            return
        end

        notify("Opening WhatsApp to send voice note to Mamoon...")

        pcall(function()
            local StrictMode = luajava.bindClass("android.os.StrictMode")
            local VmPolicyBuilder = luajava.bindClass("android.os.StrictMode$VmPolicy$Builder")
            StrictMode.setVmPolicy(VmPolicyBuilder().build())
        end)

        pcall(function() audioFileObj.setReadable(true, false) end)

        local fileUri = Uri.fromFile(audioFileObj)
        local targetJid = DEVELOPER_PHONE .. "@s.whatsapp.net"

        local sendIntent = Intent(Intent.ACTION_SEND)
        sendIntent.setType("audio/*")
        sendIntent.putExtra(Intent.EXTRA_STREAM, fileUri)
        sendIntent.putExtra("android.intent.extra.STREAM", fileUri)
        sendIntent.putExtra("jid", targetJid)
        sendIntent.putExtra(Intent.EXTRA_TEXT, "Assalam-o-Alaikum Mamoon, here is my voice feedback regarding Pro Image Recogniser.")
        sendIntent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        sendIntent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        sendIntent.setPackage("com.whatsapp")

        closeAllExtensionDialogs()

        local launched = false
        pcall(function()
            ctx.startActivity(sendIntent)
            launched = true
        end)

        if not launched then
            sendIntent.setPackage("com.whatsapp.w4b")
            pcall(function()
                ctx.startActivity(sendIntent)
                launched = true
            end)
        end

        if not launched then
            sendIntent.setPackage(nil)
            local chooser = Intent.createChooser(sendIntent, "Send Voice Note")
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            pcall(function() ctx.startActivity(chooser) end)
        end
    end

