                local dec = cjson.decode(tostring(data))
                if dec and dec.data then
                    for _, item in ipairs(dec.data) do
                        local id = tostring(item.id or "")
                        local low = id:lower()
                        if not low:find("whisper") and not low:find("tts") and not low:find("orpheus") and not low:find("guard") then
                            if isVision then
                                if low:find("qwen3%.8") or low:find("vision") or low:find("scout") or low:find("maverick") or low:find("pixtral") or low:find("llava") then
                                    table.insert(discovered, 1, id)
                                else
                                    table.insert(discovered, id)
                                end
                            else
                                table.insert(discovered, id)
                            end
                        end
                    end
                end
            end)
        end
        callback(discovered)
    end)
end

-- ==================== GROQ AI ENGINE ====================
function callGroqAI(apiKey, modelSequence, promptText, base64Image, conversationHistory, callback)
    local idx = 1
    local lastErr = "Request failed"
    local triedLiveDiscovery = false
    local baseUrl = "https://api.groq.com/openai/v1/chat/completions"

    local function tryNext()
        if idx > #modelSequence then
            if not triedLiveDiscovery then
                triedLiveDiscovery = true
                fetchLiveGroqModels(apiKey, base64Image ~= nil, function(liveList)
                    if #liveList > 0 then
                        for _, lm in ipairs(liveList) do
                            local exists = false
                            for _, em in ipairs(modelSequence) do
                                if em == lm then exists = true; break end
                            end
                            if not exists then table.insert(modelSequence, lm) end
                        end
                        tryNext()
                    else
                        runOnMain(function() callback(nil, lastErr) end)
                    end
                end)
                return
            end
            runOnMain(function() callback(nil, lastErr) end)
            return
        end

        local modelId = modelSequence[idx]
        idx = idx + 1

        local messages = {}
        if conversationHistory and #conversationHistory > 0 then
            for _, msg in ipairs(conversationHistory) do
                table.insert(messages, msg)
            end
        else
            local contentVal
            if base64Image then
                contentVal = {
                    { type = "text", text = promptText },
                    { type = "image_url", image_url = { url = "data:image/jpeg;base64," .. base64Image } }
                }
            else
                contentVal = promptText
            end
            table.insert(messages, { role = "user", content = contentVal })
        end

        local payload = cjson.encode({
            model = modelId,
            messages = messages,
            max_tokens = 600
        })

        local headers = HashMap()
        headers.put("Content-Type", "application/json")
        headers.put("Authorization", "Bearer " .. apiKey)

        safeHttpPost(baseUrl, payload, headers, function(status, data)
            local body = tostring(data or "")
            if status == 200 then
                local ok, dec = pcall(cjson.decode, body)
                if ok and dec and dec.choices and dec.choices[1] then
                    local content = dec.choices[1].message and dec.choices[1].message.content
                    if content then
                        runOnMain(function() callback(cleanAIText(content), nil) end)
                        return
                    end
                end
                lastErr = "Empty response from Groq."
                tryNext()
            elseif status == 400 or status == 404 or status == 429 or status == 503 then
                local errMsg = "HTTP Error " .. tostring(status)
                local ok, dec = pcall(cjson.decode, body)
                if ok and dec and dec.error and dec.error.message then
                    errMsg = errMsg .. ": " .. tostring(dec.error.message)
                end
                lastErr = errMsg
                tryNext()
            else
                local msg = "HTTP Error " .. tostring(status)
                local ok, dec = pcall(cjson.decode, body)
                if ok and dec and dec.error and dec.error.message then
                    msg = msg .. ": " .. tostring(dec.error.message)
                end
                runOnMain(function() callback(nil, msg) end)
            end
        end)
    end

    tryNext()
end

