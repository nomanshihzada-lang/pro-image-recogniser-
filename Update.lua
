function createMainUI()
    runOnMain(function()
        local layout = LinearLayout(ctx)
        layout.setOrientation(1)
        layout.setPadding(40, 40, 40, 40)
        layout.setBackgroundColor(LIGHT_BLUE)

        local devLabel = TextView(ctx)
        devLabel.setText("Developed by Bridge Tech (Groq)")
        devLabel.setTextColor(0xFF000000)
        devLabel.setGravity(Gravity.CENTER)
        layout.addView(devLabel)

        local btnScan = Button(ctx)
        btnScan.setText("CHOOSE FROM GALLERY")
        btnScan.onClick = function() scanAllImages() end
        layout.addView(btnScan)

        _G.statusLabel = TextView(ctx)
        _G.statusLabel.setText("No file selected")
        _G.statusLabel.setTextColor(0xFF000000)
        _G.statusLabel.setPadding(0, 20, 0, 20)
        _G.statusLabel.setGravity(Gravity.CENTER)
        layout.addView(_G.statusLabel)

        local processBtn = Button(ctx)
        processBtn.setText("Process Selected Image")
        processBtn.setBackgroundColor(0xFFFF9800)
        processBtn.onClick = function()
            if isProcessing then notify("Already processing"); return end
            if selectedPhotoPath == "" then notify("Please select an image first"); return end
            local b64 = pathToBase64(selectedPhotoPath)
            if not b64 then notify("Failed to load image"); return end
            isProcessing = true
            startProcessingSound()
            notify("Processing with Groq...")

            local prompt = buildDescriptionPrompt()

            askGroqWithHistory(prompt, b64, nil, function(res, err)
                stopProcessingSound()
                isProcessing = false
                showInteractiveResultDialog("Result & Chat (Groq)", res or ("Error: " .. tostring(err)), b64)
            end)
        end
        layout.addView(processBtn)

        local bottom = LinearLayout(ctx)
        bottom.setOrientation(0)
        bottom.setLayoutParams(LinearLayout.LayoutParams(-1, -2))

        local btnSettings = Button(ctx)
        btnSettings.setText("Settings")
        btnSettings.setLayoutParams(LinearLayout.LayoutParams(0, -2, 1))
        btnSettings.onClick = function() showSettingsDialog() end
        bottom.addView(btnSettings)

        local btnAbout = Button(ctx)
        btnAbout.setText("About")
        btnAbout.setLayoutParams(LinearLayout.LayoutParams(0, -2, 1))
        btnAbout.onClick = function() aboutAndSupport() end
        bottom.addView(btnAbout)

        local btnExit = Button(ctx)
        btnExit.setText("Exit")
        btnExit.setLayoutParams(LinearLayout.LayoutParams(0, -2, 1))
        btnExit.onClick = function() if mainDlg then mainDlg.dismiss(); mainDlg = nil end end
        bottom.addView(btnExit)

        layout.addView(bottom)

        mainDlg = LuaDialog(ctx)
        mainDlg.setTitle("Pro Image Recogniser")
        mainDlg.setView(layout)
        mainDlg.show()
        applyLightBlue(mainDlg)
    end)
end

