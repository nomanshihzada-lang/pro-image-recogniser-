function buildDescriptionPrompt()
    local lang = getSelectedLanguage()
    local langRule = LANGUAGE_INSTRUCTIONS[lang] or ("Answer in " .. tostring(lang) .. ".")
    local lenChoice = getDescriptionLength()
    local lenRule = LENGTH_INSTRUCTIONS[lenChoice] or LENGTH_INSTRUCTIONS["Medium"]
    return "Analyze this image and reply in two clearly separated sections using these exact labels:\n\n" ..
           "DESCRIPTION:\n" ..
           lenRule .. " " .. langRule .. " Put each sentence on a new line. Do not read out full text blocks inside the visual description.\n\n" ..
           "EXTRACTED_TEXT:\n" ..
           "If there is any visible text written inside the image, write all of that text here clearly line by line. If there is no text in the image, write: No text found in image.\n" ..
           "Do not use markdown or asterisks."
end

function processFocusedImage(target)
    if isProcessing then
        notify("Already processing, please wait")
        return
    end

    isProcessing = true
    startProcessingSound()
    notify("Describing image...")

    captureRegionAsBase64(target.bounds, function(b64, err)
        if b64 then
            local prompt = buildDescriptionPrompt()

            askGroqWithHistory(prompt, b64, nil, function(res, apiErr)
                stopProcessingSound()
                isProcessing = false
                local text = res or ("Error: " .. tostring(apiErr or "Request failed."))
                showInteractiveResultDialog("Result & Chat (Groq)", text, b64)
                local visualDesc, extractedText = parseDescriptionAndExtractedText(text)
                local spokenText = visualDesc
                if extractedText ~= "No text found in image." then
                    spokenText = spokenText .. ". Extracted text: " .. extractedText
                end
                pcall(function() if service and service.speak then service.speak(spokenText) end end)
            end)
        else
            stopProcessingSound()
            isProcessing = false
            local errMsg = tostring(err or "Could not capture screen.")
            notify(errMsg)
            showSimpleDialog("Capture Failed", errMsg .. "\n\nTip: You can also use 'Choose from Gallery' in the main menu.")
        end
    end)
end

