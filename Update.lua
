function safeHttpPost(url, payload, headers, callback)
    local posted = pcall(function()
        Http.post(url, payload, nil, headers, callback)
    end)
    if not posted then
        local posted4, err4 = pcall(function()
            Http.post(url, payload, headers, callback)
        end)
        if not posted4 then
            runOnMain(function() callback(-1, "Http.post error: " .. tostring(err4)) end)
        end
    end
end

function safeHttpGet(url, headers, callback)
    local got = pcall(function()
        Http.get(url, nil, nil, headers, callback)
    end)
    if not got then
        local got3 = pcall(function()
            Http.get(url, headers, callback)
        end)
        if not got3 then
            pcall(function() Http.get(url, callback) end)
        end
    end
end

