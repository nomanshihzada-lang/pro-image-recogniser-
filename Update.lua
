function scanAllImages()
    notify("Scanning gallery...")
    local found = {}
    local cr = ctx.getContentResolver()
    local uri = MediaStore.Images.Media.EXTERNAL_CONTENT_URI
    local proj = { MediaStore.Images.Media.DATA, MediaStore.Images.Media.DISPLAY_NAME }
    local c = cr.query(uri, proj, nil, nil, MediaStore.Images.Media.DATE_ADDED .. " DESC")
    if c ~= nil then
        local dcol = c.getColumnIndexOrThrow(MediaStore.Images.Media.DATA)
        local ncol = c.getColumnIndexOrThrow(MediaStore.Images.Media.DISPLAY_NAME)
        while c.moveToNext() do
            local p = c.getString(dcol)
            local n = c.getString(ncol)
            if p and n then table.insert(found, {path = p, name = n}) end
        end
        c.close()
    end
    if #found > 0 then
        runOnMain(function()
            local data = {}
            photoFilePaths = {}
            for _, f in ipairs(found) do table.insert(data, f.name); table.insert(photoFilePaths, f.path) end
            local lv = ListView(ctx)
            lv.setAdapter(ArrayAdapter(ctx, android.R.layout.simple_list_item_1, data))
            local ld = LuaDialog(ctx)
            ld.setTitle("Select Image")
            ld.setView(lv)
            ld.show()
            applyLightBlue(ld)
            lv.setOnItemClickListener(AdapterView.OnItemClickListener{
                onItemClick = function(p, v, pos, id)
                    selectedPhotoPath = photoFilePaths[pos + 1]
                    if _G.statusLabel then _G.statusLabel.setText("Selected: " .. File_CLASS(selectedPhotoPath).getName()) end
                    notify("Selected: " .. File_CLASS(selectedPhotoPath).getName())
                    ld.dismiss()
                end
            })
        end)
    else
        showSimpleDialog("Gallery", "No images found.")
    end
end

