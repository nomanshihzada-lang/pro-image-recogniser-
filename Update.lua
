function getCurrentFocusedItem()
    local n = nil
    pcall(function()
        local root = service.getRootInActiveWindow and service.getRootInActiveWindow() or nil
        if root then
            local f = root.findFocus(2)
            if f then n = f end
        end
    end)
    if n then return n end
    pcall(function() if service.getFocusView then n = service.getFocusView() end end)
    if n then return n end
    pcall(function() if service.getCurrentNode then n = service.getCurrentNode() end end)
    return n
end

local IMAGE_CLASS_HINTS = { "imageview", "imagebutton", "image", "picture", "photo", "avatar", "thumbnail", "icon" }

function resolveTargetImage()
    local focused = getCurrentFocusedItem()
    if not focused then return nil end

    local className = ""
    pcall(function() className = string.lower(tostring(focused.getClassName() or "")) end)

    if className:find("textview", 1, true) or className:find("layout", 1, true) or className:find("edittext", 1, true) then
        return nil
    end

    local isImg = false
    for _, hint in ipairs(IMAGE_CLASS_HINTS) do
        if className:find(hint, 1, true) then isImg = true; break end
    end

    local rect = Rect()
    pcall(function() focused.getBoundsInScreen(rect) end)
    local w = rect.right - rect.left
    local h = rect.bottom - rect.top

    if isImg and w >= 64 and h >= 64 then
        return {
            bounds = { left = rect.left, top = rect.top, right = rect.right, bottom = rect.bottom }
        }
    end

    return nil
end

function pathToBase64(imagePath)
    if not imagePath or imagePath == "" then return nil end
    local f = File_CLASS(imagePath)
    if not f.exists() or not f.canRead() then return nil end
    local options = BitmapFactory.Options()
    options.inSampleSize = 2
    local bmp = BitmapFactory.decodeFile(imagePath, options)
    if not bmp then return nil end
    local out = ByteArrayOutputStream()
    bmp.compress(Bitmap.CompressFormat.JPEG, 60, out)
    local bytes = out.toByteArray()
    out.close()
    pcall(function() bmp.recycle() end)
    return Base64.encodeToString(bytes, Base64.NO_WRAP)
end

-- ==================== SCREEN CAPTURE & CROP ENGINE ====================
function captureRegionAsBase64(bounds, callback)
    local bv = luajava.bindClass("android.os.Build$VERSION")
    if bv.SDK_INT < 30 then
        callback(nil, "Screen capture requires Android 11 or higher.")
        return
    end
    if not hasConsent() then
        callback(nil, "Screen capture permission is not enabled in Settings.")
        return
    end

    local done = { hit = false }
    local timeoutRunnable = nil

    local function finish(b64, err)
        if done.hit then return end
        done.hit = true
        if timeoutRunnable then
            pcall(function() mainHandler.removeCallbacks(timeoutRunnable) end)
            timeoutRunnable = nil
        end
        runOnMain(function() callback(b64, err) end)
    end

    timeoutRunnable = Runnable({
        run = function()
            finish(nil, "Screenshot timed out (CSR did not return screen buffer in 5 seconds).")
        end
    })
    mainHandler.postDelayed(timeoutRunnable, 5000)

    local cbOk, cb = pcall(function()
        return luajava.createProxy("android.accessibilityservice.AccessibilityService$TakeScreenshotCallback", {
            onSuccess = function(res)
                local ok, errObj = pcall(function()
                    local hb = res.getHardwareBuffer()
                    local cs = res.getColorSpace()
                    local hw = Bitmap.wrapHardwareBuffer(hb, cs)
                    if not hw then
                        pcall(function() hb.close() end)
                        finish(nil, "Failed to wrap hardware buffer.")
                        return
                    end

                    local soft = hw.copy(Bitmap.Config.ARGB_8888, false)
                    pcall(function() hw.recycle() end)
                    pcall(function() hb.close() end)

                    if not soft then
                        finish(nil, "Failed to copy hardware bitmap to software memory.")
                        return
                    end

                    local bmW, bmH = soft.getWidth(), soft.getHeight()
                    local sw, sh = bmW, bmH
                    pcall(function()
                        local dm = ctx.getResources().getDisplayMetrics()
                        sw, sh = dm.widthPixels, dm.heightPixels
                    end)
                    local scaleX, scaleY = bmW / sw, bmH / sh

                    local rx, ry, rw, rh = 0, 0, bmW, bmH
                    if bounds and bounds.left and bounds.right then
                        rx = math.max(0, math.min(math.floor(bounds.left * scaleX), bmW - 1))
                        ry = math.max(0, math.min(math.floor(bounds.top * scaleY), bmH - 1))
                        rw = math.max(1, math.min(math.floor((bounds.right - bounds.left) * scaleX), bmW - rx))
                        rh = math.max(1, math.min(math.floor((bounds.bottom - bounds.top) * scaleY), bmH - ry))
                    end

                    local region = soft
                    if rw < bmW or rh < bmH then
                        pcall(function()
                            local cropped = Bitmap.createBitmap(soft, rx, ry, rw, rh)
                            if cropped then region = cropped end
                        end)
                    end

                    local maxSide = math.max(region.getWidth(), region.getHeight())
                    if maxSide > 800 then
                        local scale = 800 / maxSide
                        pcall(function()
                            local scaled = Bitmap.createScaledBitmap(
                                region,
                                math.floor(region.getWidth() * scale),
                                math.floor(region.getHeight() * scale),
                                true
                            )
                            if scaled then region = scaled end
                        end)
                    end

                    local baos = ByteArrayOutputStream()
                    region.compress(Bitmap.CompressFormat.JPEG, 60, baos)
                    local b64 = Base64.encodeToString(baos.toByteArray(), Base64.NO_WRAP)
                    baos.close()

                    pcall(function() if region ~= soft then region.recycle() end end)
                    pcall(function() soft.recycle() end)

                    finish(b64, nil)
                end)
                if not ok then
                    finish(nil, "Image processing error: " .. tostring(errObj))
                end
            end,
            onFailure = function(code)
                finish(nil, "Android rejected screenshot with error code: " .. tostring(code))
            end
        })
    end)

    if not cbOk or not cb then
        finish(nil, "Could not create screenshot callback proxy.")
        return
    end

    local executor = nil
    pcall(function() executor = ctx.getMainExecutor() end)
    if not executor then
        pcall(function()
            executor = luajava.createProxy("java.util.concurrent.Executor", {
                execute = function(r) runOnMain(function() r.run() end) end
            })
        end)
    end

    mainHandler.post(Runnable({
        run = function()
            local callOk, callErr = pcall(function()
                service.takeScreenshot(0, executor, cb)
            end)
            if not callOk then
                finish(nil, "takeScreenshot failed to launch: " .. tostring(callErr))
            end
        end
    }))
end

-- ==================== TEXT CLEANING & OCR PARSERS ====================
function cleanAIText(t)
    if not t then return t end
    local s = tostring(t)
    s = s:gsub("<think>.-</think>", "")
    s = s:gsub("%*", ""):gsub("`", ""):gsub("#+%s*", ""):gsub("_", "")
    return s:match("^%s*(.-)%s*$") or s
end

function parseDescriptionAndExtractedText(rawText)
    local s = tostring(rawText or "")
    local descPart = s
    local textPart = "No text found in image."

    local splitPos = s:find("EXTRACTED_TEXT:", 1, true)
    if not splitPos then
        splitPos = s:find("Extracted Text:", 1, true)
    end

    if splitPos then
        descPart = s:sub(1, splitPos - 1)
        textPart = s:sub(splitPos):gsub("^[Ee][Xx][Tt][Rr][Aa][Cc][Tt][Ee][Dd]_[Tt][Ee][Xx][Tt]:%s*", ""):gsub("^[Ee]xtracted [Tt]ext:%s*", "")
    end

    descPart = descPart:gsub("^[Dd][Ee][Ss][Cc][Rr][Ii][Pp][Tt][Ii][Oo][Nn]:%s*", ""):gsub("^[Dd]escription:%s*", "")
    descPart = descPart:match("^%s*(.-)%s*$") or ""
    textPart = textPart:match("^%s*(.-)%s*$") or ""

    if descPart == "" then descPart = s end
    if textPart == "" or textPart:lower() == "none" or textPart:lower() == "none." or textPart:lower() == "n/a" then
        textPart = "No text found in image."
    end

    return descPart, textPart
end

function splitTextIntoListItems(text)
    local items = {}
    local raw = tostring(text or "")
    for line in raw:gmatch("[^\r\n]+") do
        local cleanLine = line:match("^%s*(.-)%s*$")
        if cleanLine and cleanLine ~= "" then
            local buffer = ""
            for i = 1, #cleanLine do
                local ch = cleanLine:sub(i, i)
                buffer = buffer .. ch
                if ch == "." or ch == "!" or ch == "?" then
                    local nextCh = cleanLine:sub(i + 1, i + 1)
                    if nextCh == "" or nextCh == " " then
                        local trimmed = buffer:match("^%s*(.-)%s*$")
                        if trimmed ~= "" then table.insert(items, trimmed) end
                        buffer = ""
                    end
                end
            end
            local rem = buffer:match("^%s*(.-)%s*$")
            if rem and rem ~= "" then
                table.insert(items, rem)
            end
        end
    end
    if #items == 0 then
        table.insert(items, raw ~= "" and raw or "(No text)")
    end
    return items
end

